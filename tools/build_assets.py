"""Build every image derivative the catalog needs and write manifest.json.

Usage:
    python tools/build_assets.py                 # incremental build
    python tools/build_assets.py --only products # products | banners | logos
    python tools/build_assets.py --force         # ignore the cache
    python tools/build_assets.py --check         # resolve only; exit 1 if any key is missing
    python tools/build_assets.py -v

Sources are resolved in this order for every key in assets_src/required_keys.txt:
    1. assets_src/overrides.json  (explicit key -> PNG under PRODUCT_SRC)
    2. PRODUCT_SRC/**/<key>.png   (master photos, read-only company_db)
    3. config.MIRROR               (left/right pairs generated by flipping)
    4. config.ALIAS                (legacy keys that duplicate a spread image)
    5. assets_src/legacy/products/<key>.webp (extracted from the old HTML)
    6. -> missing.txt
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

from PIL import Image, ImageOps

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tools import config  # noqa: E402

Image.MAX_IMAGE_PIXELS = 50_000_000


# --------------------------------------------------------------------------- types
@dataclass
class Source:
    path: Path
    origin: str            # company_db | override | mirror | alias | legacy
    mirror: bool = False


@dataclass
class Report:
    sources: dict = field(default_factory=dict)
    duplicates: list = field(default_factory=list)
    unused_png: list = field(default_factory=list)
    upscale_capped: list = field(default_factory=list)
    license_unverified: list = field(default_factory=list)
    warnings: list = field(default_factory=list)
    built: int = 0
    skipped: int = 0
    missing: list = field(default_factory=list)


# --------------------------------------------------------------------------- helpers
def _load_json(path: Path, default):
    if not path.exists():
        return default
    data = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(data, dict):
        data.pop("_comment", None)
    return data


def _sha8(data: bytes) -> str:
    return hashlib.sha1(data).hexdigest()[:8]


def _resize_w(im: Image.Image, width: int) -> Image.Image:
    if im.width == width:
        return im
    h = max(1, round(im.height * width / im.width))
    return im.resize((width, h), Image.LANCZOS)


def _crop_ratio(im: Image.Image, ratio: float, focus) -> Image.Image:
    w, h = im.size
    fx, fy = focus
    if w / h > ratio:
        nw = int(round(h * ratio))
        x0 = min(max(int(w * fx - nw / 2), 0), w - nw)
        return im.crop((x0, 0, x0 + nw, h))
    nh = int(round(w / ratio))
    y0 = min(max(int(h * fy - nh / 2), 0), h - nh)
    return im.crop((0, y0, w, y0 + nh))


def _encode(im: Image.Image, fmt: str, **kw) -> bytes:
    buf = io.BytesIO()
    im.save(buf, fmt, **kw)
    return buf.getvalue()


# --------------------------------------------------------------------------- cache
class Cache:
    def __init__(self, path: Path, force: bool):
        self.path = path
        self.force = force
        self.data = {} if force else _load_json(path, {})
        self.touched: set[str] = set()

    @staticmethod
    def _sig(src: Path, params: str) -> dict:
        st = src.stat()
        return {"src": str(src), "mtime_ns": st.st_mtime_ns, "size": st.st_size, "params": params}

    def get(self, logical: str, src: Path, params: str) -> dict | None:
        ent = self.data.get(logical)
        if not ent:
            return None
        sig = self._sig(src, params)
        if all(ent.get(k) == v for k, v in sig.items()) and (config.OUT / ent["out"]).exists():
            self.touched.add(logical)
            return ent
        return None

    def put(self, logical: str, src: Path, params: str, out: str, w: int, h: int) -> dict:
        ent = {**self._sig(src, params), "out": out, "w": w, "h": h}
        self.data[logical] = ent
        self.touched.add(logical)
        return ent

    def save(self, prune: bool = True) -> None:
        if prune:  # a full build drops entries no longer produced; partial builds keep them
            self.data = {k: v for k, v in self.data.items() if k in self.touched}
        self.path.write_text(json.dumps(self.data, ensure_ascii=False, indent=0, sort_keys=True), encoding="utf-8")


# --------------------------------------------------------------------------- builder
class Builder:
    def __init__(self, force: bool = False, verbose: bool = False):
        self.verbose = verbose
        self.report = Report()
        self.cache = Cache(config.CACHE, force)
        self.manifest = {"version": 1, "built": None, "products": {}, "banners": {}, "images": {}}
        self.required = [k for k in config.REQUIRED_KEYS.read_text(encoding="utf-8").split() if k]
        self.overrides: dict = _load_json(config.OVERRIDES_JSON, {})
        self.banners_cfg: dict = _load_json(config.BANNERS_JSON, {})
        self.legacy_index: dict = _load_json(config.LEGACY / "legacy_index.json", {})
        config.assert_safe_output(config.OUT)
        config.OUT.mkdir(parents=True, exist_ok=True)

    def log(self, *a):
        if self.verbose:
            print(*a)

    # ---- source resolution -------------------------------------------------
    def scan_products(self) -> dict[str, list[Path]]:
        found: dict[str, list[Path]] = {}
        if not config.PRODUCT_SRC.exists():
            self.report.warnings.append(f"PRODUCT_SRC not found: {config.PRODUCT_SRC}")
            return found
        for p in sorted(config.PRODUCT_SRC.rglob("*.png"), key=lambda p: str(p).casefold()):
            found.setdefault(p.stem, []).append(p)
        for stem, paths in found.items():
            if len(paths) > 1:
                self.report.duplicates.append((stem, [str(x.relative_to(config.PRODUCT_SRC)) for x in paths]))
        return found

    def resolve_sources(self) -> dict[str, Source]:
        scanned = self.scan_products()
        out: dict[str, Source] = {}
        for key in self.required:
            src = self._resolve_one(key, scanned)
            if src is None:
                self.report.missing.append(key)
            else:
                out[key] = src
                self.report.sources[src.origin] = self.report.sources.get(src.origin, 0) + 1
        used_stems = {s.path.stem for s in out.values() if s.origin in ("company_db", "override")}
        self.report.unused_png = sorted(set(scanned) - used_stems)
        return out

    def _resolve_one(self, key: str, scanned: dict[str, list[Path]]) -> Source | None:
        if key in self.overrides:
            p = config.PRODUCT_SRC / self.overrides[key]
            if p.exists():
                return Source(p, "override")
            self.report.warnings.append(f"override target missing for {key}: {p}")
        if key in scanned:
            return Source(scanned[key][0], "company_db")
        if key in config.MIRROR:
            base = self._resolve_one(config.MIRROR[key], scanned)
            if base:
                return Source(base.path, "mirror", mirror=True)
        if key in config.ALIAS:
            p = config.LEGACY / "images" / f"{config.ALIAS[key]}.webp"
            if p.exists():
                return Source(p, "alias")
        p = config.LEGACY / "products" / f"{key}.webp"
        if p.exists():
            return Source(p, "legacy")
        return None

    # ---- derivatives -------------------------------------------------------
    def _emit(self, logical: str, src: Path, params: str, make, sub: str, name: str, ext: str) -> dict:
        """Run make() -> (Image, save_kwargs, fmt) unless cached; return manifest fragment."""
        hit = self.cache.get(logical, src, params)
        if hit:
            self.report.skipped += 1
            return {"p": f"img/{hit['out']}", "w": hit["w"], "h": hit["h"]}
        im, kw, fmt = make()
        data = _encode(im, fmt, **kw)
        rel = f"{sub}/{name}.{_sha8(data)}.{ext}"
        path = config.OUT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        self.cache.put(logical, src, params, rel, im.width, im.height)
        self.report.built += 1
        self.log("built", rel, f"{len(data)//1024} KB")
        return {"p": f"img/{rel}", "w": im.width, "h": im.height}

    def build_products(self, sources: dict[str, Source]) -> None:
        for key, src in sources.items():
            with Image.open(src.path) as raw:
                has_alpha = "A" in raw.getbands() or raw.mode == "P"
                im = ImageOps.exif_transpose(raw).convert("RGBA")
                if src.mirror:
                    im = ImageOps.mirror(im)
            full_w = min(im.width, config.FULL_MAX)
            widths = {**config.PRODUCT_WIDTHS, "f": full_w}
            entry: dict = {"w": im.width, "h": im.height, "origin": src.origin, "alt": key, "alpha": has_alpha}
            if src.mirror:
                entry["mirrored"] = True
            for var, target in widths.items():
                w = min(target, im.width)
                if target > im.width and var != "f":
                    self.report.upscale_capped.append(f"{key}:{var} {target}->{im.width}")
                params = f"w{w} q{config.PRODUCT_Q} m{config.WEBP_METHOD} mirror{int(src.mirror)}"
                suffix = {"t": str(config.PRODUCT_WIDTHS["t"]), "m": str(config.PRODUCT_WIDTHS["m"]), "f": "full"}[var]

                def make(im=im, w=w):
                    return (_resize_w(im, w), {"quality": config.PRODUCT_Q, "method": config.WEBP_METHOD}, "WEBP")

                frag = self._emit(f"products/{key}/{var}", src.path, params, make, "products", f"{key}-{suffix}", "webp")
                entry[var] = frag["p"]
                entry[var + "w"] = frag["w"]
            self.manifest["products"][key] = entry

    def _photo_source(self, name: str, cfg: dict) -> Path | None:
        src = cfg.get("src", "legacy")
        if src == "legacy":
            sub = "banners" if (name == "hero" or name.startswith("band_")) else "images"
            p = config.LEGACY / sub / f"{name}.webp"
        else:
            p = config.ROOT / src
        if not p.exists():
            self.report.warnings.append(f"{name}: source not found {p}")
            return None
        if cfg.get("license", "unknown") == "unverified":
            self.report.license_unverified.append(f"{name} <- {src}")
        return p

    def build_banners(self) -> None:
        for name, cfg in self.banners_cfg.items():
            p = self._photo_source(name, cfg)
            if p is None:
                continue
            is_hero = name == "hero"
            is_band = name.startswith("band_")
            is_photo = is_hero or is_band
            ratio = cfg.get("ratio") or (config.HERO_RATIO if is_hero else config.BANNER_RATIO if is_band else None)
            gray = cfg.get("gray", is_photo or cfg.get("src", "legacy") != "legacy")
            with Image.open(p) as raw:
                im = ImageOps.exif_transpose(raw)
                im = im.convert("RGBA") if ("A" in im.getbands() and not is_photo) else im.convert("RGB")
            if ratio:
                im = _crop_ratio(im, ratio, cfg.get("focus", [0.5, 0.5]))
            if gray:
                im = ImageOps.grayscale(im).convert("RGB") if im.mode == "RGB" else im
            widths = config.HERO_WIDTHS if is_hero else config.BANNER_WIDTHS if is_band else config.SPREAD_WIDTHS
            q = config.BANNER_Q if is_photo else config.SPREAD_Q
            entry: dict = {"w": im.width, "h": im.height, "src": cfg.get("src", "legacy"),
                           "license": cfg.get("license", "unknown")}
            for var, target in widths.items():
                w = min(target, im.width)
                if target > im.width:
                    self.report.upscale_capped.append(f"{name}:{var} {target}->{im.width}")
                params = f"w{w} q{q} gray{int(gray)} ratio{entry['w']}x{entry['h']} m{config.WEBP_METHOD}"

                def make(im=im, w=w, q=q):
                    return (_resize_w(im, w), {"quality": q, "method": config.WEBP_METHOD}, "WEBP")

                sub = "banners" if is_photo else "misc"
                frag = self._emit(f"{sub}/{name}/{var}", p, params, make, sub, f"{name}-{var}", "webp")
                entry[var] = frag["p"]
                entry[var + "w"] = frag["w"]
            target = self.manifest["banners"] if is_photo else self.manifest["images"]
            target[name] = entry

    def build_logo(self) -> None:
        p = config.LOGO_SRC
        if not p.exists():
            legacy = config.LEGACY / "images" / "logo_top.webp"
            self.report.warnings.append(f"LOGO_SRC not found ({p}); using legacy logo")
            p = legacy
        with Image.open(p) as raw:
            im = raw.convert("RGBA")
        if im.width > config.LOGO_MAX_W:
            im = _resize_w(im, config.LOGO_MAX_W)
        # The catalogue is monochrome and the CSS inverts the logo per surface, so any
        # coloured accent (the NEW logo has a red mark) is flattened to white, alpha kept.
        px = [c for c in im.get_flattened_data() if c[3] > 128]
        if px:
            nonwhite = sum(1 for c in px if min(c[:3]) < 200) / len(px)
            if nonwhite:
                self.report.warnings.append(f"logo: {nonwhite:.1%} of opaque pixels were not white -> flattened to white")
        alpha = im.getchannel("A")
        im = Image.new("RGBA", im.size, (255, 255, 255, 0))
        im.putalpha(alpha)
        params = f"w{im.width} png mono"

        def make(im=im):
            return (im, {"optimize": True}, "PNG")

        frag = self._emit("logo/gssem-white", p, params, make, "logo", "gssem-white", "png")
        self.manifest["images"]["logo"] = {"p": frag["p"], "w": frag["w"], "h": frag["h"]}

    # ---- outputs -----------------------------------------------------------
    def prune(self) -> None:
        keep = set()

        def walk(o):
            if isinstance(o, dict):
                for v in o.values():
                    walk(v)
            elif isinstance(o, str) and o.startswith("img/"):
                keep.add(o[4:])

        walk(self.manifest)
        for sub in ("products", "banners", "misc", "logo"):
            d = config.OUT / sub
            if not d.exists():
                continue
            for f in d.iterdir():
                if f.is_file() and f"{sub}/{f.name}" not in keep:
                    f.unlink()
                    self.log("pruned", f.name)

    def write(self, partial: bool = False) -> None:
        self.manifest["built"] = time.strftime("%Y-%m-%dT%H:%M:%S")
        self.manifest["counts"] = {k: len(v) for k, v in self.manifest.items() if isinstance(v, dict)}
        self.manifest["license_unverified"] = len(self.report.license_unverified)
        config.MANIFEST.write_text(json.dumps(self.manifest, ensure_ascii=False, indent=1, sort_keys=True), encoding="utf-8")
        config.MISSING.write_text("\n".join(self.report.missing) + ("\n" if self.report.missing else ""), encoding="utf-8")
        r = self.report
        lines = [f"build_report {self.manifest['built']}", ""]
        lines += ["SOURCES"] + [f"  {k}: {v}" for k, v in sorted(r.sources.items())] + [""]
        lines += [f"BUILT {r.built}  SKIPPED(cache) {r.skipped}", ""]
        lines += [f"MISSING ({len(r.missing)})"] + [f"  {k}" for k in r.missing] + [""]
        lines += [f"DUPLICATES ({len(r.duplicates)})"] + [f"  {s}: {p}" for s, p in r.duplicates] + [""]
        lines += [f"UNUSED_PNG ({len(r.unused_png)})"] + [f"  {k}" for k in r.unused_png] + [""]
        lines += [f"UPSCALE_CAPPED ({len(r.upscale_capped)})"] + [f"  {k}" for k in r.upscale_capped] + [""]
        lines += [f"LICENSE_UNVERIFIED ({len(r.license_unverified)})"] + [f"  {k}" for k in r.license_unverified] + [""]
        lines += [f"WARNINGS ({len(r.warnings)})"] + [f"  {k}" for k in r.warnings] + [""]
        total = sum(f.stat().st_size for f in config.OUT.rglob("*") if f.is_file())
        lines += [f"OUTPUT_SIZE {total/1_048_576:.1f} MB"]
        config.REPORT.write_text("\n".join(lines), encoding="utf-8")
        self.cache.save(prune=not partial)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", choices=["products", "banners", "logos"])
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--check", action="store_true", help="resolve sources only; exit 1 on missing")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args(argv)

    b = Builder(force=args.force, verbose=args.verbose)
    sources = b.resolve_sources()
    if args.check:
        for k, v in sorted(b.report.sources.items()):
            print(f"{k}: {v}")
        print("missing:", b.report.missing or "none")
        return 1 if b.report.missing else 0

    if args.only:
        # partial build: keep other sections from the existing manifest
        old = _load_json(config.MANIFEST, {})
        for sec in ("products", "banners", "images"):
            b.manifest[sec] = old.get(sec, {})
    if args.only in (None, "products"):
        b.manifest["products"] = {}
        b.build_products(sources)
    if args.only in (None, "banners"):
        b.manifest["banners"] = {}
        b.manifest["images"] = {k: v for k, v in b.manifest["images"].items() if k == "logo"}
        b.build_banners()
    if args.only in (None, "logos"):
        b.build_logo()
    if not args.only:
        b.prune()
    b.write(partial=bool(args.only))
    print(config.REPORT.read_text(encoding="utf-8"))
    return 1 if b.report.missing else 0


if __name__ == "__main__":
    sys.exit(main())
